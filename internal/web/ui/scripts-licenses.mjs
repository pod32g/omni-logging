// Collects licence texts for everything that ends up in the shipped bundle.
// Minification strips banner comments, so the notices have to travel beside the
// bundle instead of inside it — MIT requires them to accompany the code.
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
// Runtime dependencies, plus anything they pull in that is bundled.
const roots = Object.keys(pkg.dependencies);
const seen = new Map();

function visit(name) {
  if (seen.has(name)) return;
  const dir = join("node_modules", name);
  if (!existsSync(dir)) return;
  const meta = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const licFile = readdirSync(dir).find((f) => /^(LICENSE|LICENCE|COPYING)/i.test(f));
  seen.set(name, {
    version: meta.version,
    license: meta.license ?? "see text",
    text: licFile ? readFileSync(join(dir, licFile), "utf8").trim() : "(no licence file shipped)",
    homepage: meta.homepage ?? meta.repository?.url ?? "",
  });
  for (const dep of Object.keys(meta.dependencies ?? {})) visit(dep);
}
roots.forEach(visit);

const names = [...seen.keys()].sort();
let out =
  "Third-party software bundled into the Omni-logging web UI\n" +
  "=========================================================\n\n" +
  "The UI is compiled into a single JavaScript bundle that is embedded in the\n" +
  "omnilog binary. Minification strips banner comments, so the licence notices\n" +
  "for the bundled packages are reproduced here in full.\n\n" +
  "Generated by scripts-licenses.mjs — run `npm run licenses` after changing\n" +
  "dependencies.\n\n";
for (const n of names) {
  const m = seen.get(n);
  out += `${"-".repeat(72)}\n${n} ${m.version} — ${m.license}\n${m.homepage}\n${"-".repeat(72)}\n\n${m.text}\n\n`;
}
writeFileSync("public/THIRD-PARTY.txt", out);
console.log(`wrote public/THIRD-PARTY.txt for ${names.length} packages: ${names.join(", ")}`);
